-- AI 옷장 공개 배포용 Supabase 스키마
-- Supabase 대시보드 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
-- 여러 번 실행해도 안전하다 (있으면 건너뜀).
--
-- 원칙
-- 1) 모든 표에 user_id(로그인 사용자 id)를 두고, 행 단위 보안(RLS)으로 "내 행만 읽고 쓰기"를 강제한다.
-- 2) 앱은 공개 키(anon/publishable) + 로그인 토큰으로만 접근한다. service_role 키는 앱에 넣지 않는다.
-- 3) 값의 형태는 로컬 SQLite 판(core/db.py)과 같게 둔다 (0/1 정수, JSON 문자열, ISO 시각 문자열).

