-- ------------------------------------------------------------ 기록 조회용 뷰 (core/db.py 의 SQL 과 같은 조인·집계)
-- 여러 표를 앱에서 내려받아 잇지 않고 DB에서 잇는다. security_invoker: 부른 사용자의 RLS 가 아래 표에 그대로 적용된다
-- (PostgreSQL 15 이상). 앱은 정렬을 정해 한도(Supabase 기본 1,000줄)씩 끝까지 나눠 받는다.
create or replace view public.saved_outfit_rows with (security_invoker = true) as
select s.id, s.user_id, s.saved_at, r.rank, r.score, r.pieces_json, rs.purpose, rs.temperature, rs.humidity
  from public.saved_outfits s
  join public.recommendations r on r.id = s.recommendation_id
  join public.recommendation_sessions rs on rs.id = r.session_id;

create or replace view public.disliked_outfit_rows with (security_invoker = true) as
select f.id, f.user_id, r.pieces_json
  from public.feedback f
  join public.recommendations r on r.id = f.recommendation_id
  join public.recommendation_sessions rs on rs.id = r.session_id
 where f.rating = 'dislike' and rs.user_id = f.user_id;

-- 추천 로그 CSV: 세션마다 추천 줄(없으면 세션만 한 줄) + 피드백
create or replace view public.recommendation_log_rows with (security_invoker = true) as
select rs.user_id, rs.id as session_id, rs.started_at, rs.completed_at, rs.purpose, rs.temperature,
       rs.apparent_temperature, rs.humidity, rs.precipitation, rs.rain, rs.wind_speed, rs.weather_source,
       r.id as recommendation_id, r.rank, r.score, r.pieces_json,
       f.rating, f.worn, f.thermal_feedback, f.satisfaction
  from public.recommendation_sessions rs
  left join public.recommendations r on r.session_id = rs.id
  left join public.feedback f on f.recommendation_id = r.id and f.user_id = rs.user_id;

-- KPI 한 줄: 추천 세션 수, 코디를 저장한 세션 수 (RLS 가 내 행만 남긴다)
create or replace view public.kpi_rows with (security_invoker = true) as
select (select count(*) from public.recommendation_sessions) as sessions,
       (select count(distinct r.session_id)
          from public.saved_outfits s
          join public.recommendations r on r.id = s.recommendation_id
          join public.recommendation_sessions rs on rs.id = r.session_id
         where rs.user_id = s.user_id) as accepted_sessions;

-- 추천 로그 CSV 전체를 JSON 하나로 (core/db.py export_user_logs 와 같은 열·순서). 한 문장이라 한 시점의 결과이고,
-- 표가 아니라 값 하나를 돌려줘서 API 반환 줄 한도(기본 1,000줄)를 받지 않는다. 옷 이름 줄(outfit)은 여기서 만든다.
create or replace function public.export_user_logs()
returns jsonb
language sql stable security invoker set search_path = ''
as $$
    select coalesce(jsonb_agg(jsonb_build_object(
               'session_id', l.session_id, 'started_at', l.started_at, 'completed_at', l.completed_at,
               'purpose', l.purpose, 'temperature', l.temperature, 'apparent_temperature', l.apparent_temperature,
               'humidity', l.humidity, 'precipitation', l.precipitation, 'rain', l.rain, 'wind_speed', l.wind_speed,
               'weather_source', l.weather_source, 'recommendation_id', l.recommendation_id, 'rank', l.rank,
               'score', l.score, 'rating', l.rating, 'worn', l.worn, 'thermal_feedback', l.thermal_feedback,
               'satisfaction', l.satisfaction,
               'outfit', case when l.pieces_json is null then null else coalesce(
                   (select string_agg(p.v ->> 'name', ' + ' order by p.o)
                      from jsonb_array_elements(l.pieces_json::jsonb) with ordinality as p(v, o)), '') end)
             order by l.session_id desc, l.rank asc nulls first, l.recommendation_id asc nulls first), '[]'::jsonb)
      from public.recommendation_log_rows l
     where l.user_id = (select auth.uid())
$$;
revoke execute on function public.export_user_logs() from public, anon;
grant execute on function public.export_user_logs() to authenticated;

