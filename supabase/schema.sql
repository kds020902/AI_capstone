-- AI 옷장 공개 배포용 Supabase 스키마
-- Supabase 대시보드 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
-- 여러 번 실행해도 안전하다 (있으면 건너뜀).
--
-- 원칙
-- 1) 모든 표에 user_id(로그인 사용자 id)를 두고, 행 단위 보안(RLS)으로 "내 행만 읽고 쓰기"를 강제한다.
-- 2) 앱은 공개 키(anon/publishable) + 로그인 토큰으로만 접근한다. service_role 키는 앱에 넣지 않는다.
-- 3) 값의 형태는 로컬 SQLite 판(core/db.py)과 같게 둔다 (0/1 정수, JSON 문자열, ISO 시각 문자열).

-- ------------------------------------------------------------ 표
create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    name text not null,
    gender text not null default 'male',
    cold_sensitivity double precision not null default 0.4,
    heat_sensitivity double precision not null default 0.4,
    baseline_decision_seconds double precision not null default 180,
    created_at text not null
);

create table if not exists public.wardrobe_items (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    name text not null,
    category text not null,
    subcategory text,
    color text,
    warmth integer not null,
    rain_ok integer not null,
    material text,
    image_path text,
    notes text,
    ai_category text,
    ai_subcategory text,
    ai_confidence double precision,
    seasons text,
    active integer not null default 1,
    deleted integer not null default 0,
    created_at text not null
);
create index if not exists wardrobe_items_user_idx on public.wardrobe_items (user_id);

create table if not exists public.recommendation_sessions (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    purpose text not null,
    temperature double precision not null,
    apparent_temperature double precision,
    humidity double precision not null,
    precipitation double precision not null,
    rain integer not null,
    wind_speed double precision not null,
    weather_source text not null,
    started_at text not null,
    completed_at text,
    decision_seconds double precision
);
create index if not exists recommendation_sessions_user_idx on public.recommendation_sessions (user_id);

create table if not exists public.recommendations (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    session_id bigint not null references public.recommendation_sessions (id) on delete cascade,
    rank integer not null,
    score double precision not null,
    pieces_json text not null,
    reasons_json text not null,
    components_json text not null,
    created_at text not null
);
create index if not exists recommendations_user_idx on public.recommendations (user_id);

create table if not exists public.saved_outfits (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    recommendation_id bigint not null references public.recommendations (id) on delete cascade,
    saved_at text not null,
    unique (user_id, recommendation_id)
);

create table if not exists public.feedback (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    recommendation_id bigint not null references public.recommendations (id) on delete cascade,
    rating text,
    worn integer,
    thermal_feedback integer,
    satisfaction integer,
    updated_at text not null,
    unique (user_id, recommendation_id)
);

-- 사기 전에 맞춰보기: 아직 안 산 옷 (옷장과 따로 둬서 추천에 섞이지 않게)
create table if not exists public.purchase_candidates (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    name text not null,
    category text not null,
    subcategory text,
    color text,
    warmth integer not null,
    rain_ok integer not null,
    image_path text,
    link text,
    ai_subcategory text,
    ai_confidence double precision,
    deleted integer not null default 0,
    created_at text not null
);
create index if not exists purchase_candidates_user_idx on public.purchase_candidates (user_id);

-- ------------------------------------------------------------ 권한: 로그인한 사용자만, 그리고 자기 행만
revoke all on public.profiles, public.wardrobe_items, public.recommendation_sessions, public.recommendations,
    public.saved_outfits, public.feedback, public.purchase_candidates from anon;
grant select, insert, update, delete on public.profiles, public.wardrobe_items, public.recommendation_sessions,
    public.recommendations, public.saved_outfits, public.feedback, public.purchase_candidates to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.profiles enable row level security;
alter table public.wardrobe_items enable row level security;
alter table public.recommendation_sessions enable row level security;
alter table public.recommendations enable row level security;
alter table public.saved_outfits enable row level security;
alter table public.feedback enable row level security;
alter table public.purchase_candidates enable row level security;

drop policy if exists "own profile" on public.profiles;
create policy "own profile" on public.profiles for all to authenticated
    using (id = (select auth.uid())) with check (id = (select auth.uid()));

drop policy if exists "own items" on public.wardrobe_items;
create policy "own items" on public.wardrobe_items for all to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists "own sessions" on public.recommendation_sessions;
create policy "own sessions" on public.recommendation_sessions for all to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists "own candidates" on public.purchase_candidates;
create policy "own candidates" on public.purchase_candidates for all to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- 하위 표는 "가리키는 상위 행도 내 것"까지 확인한다 (외래 키 검사는 RLS를 거치지 않기 때문)
drop policy if exists "own recommendations" on public.recommendations;
create policy "own recommendations" on public.recommendations for all to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()) and exists (
        select 1 from public.recommendation_sessions s where s.id = session_id and s.user_id = (select auth.uid())));

drop policy if exists "own saved outfits" on public.saved_outfits;
create policy "own saved outfits" on public.saved_outfits for all to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()) and exists (
        select 1 from public.recommendations r where r.id = recommendation_id and r.user_id = (select auth.uid())));

drop policy if exists "own feedback" on public.feedback;
create policy "own feedback" on public.feedback for all to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()) and exists (
        select 1 from public.recommendations r where r.id = recommendation_id and r.user_id = (select auth.uid())));

-- ------------------------------------------------------------ 사진 저장소 (비공개 버킷)
-- 경로는 "<사용자 id>/<파일 이름>". 첫 폴더가 내 id인 파일만 읽고 쓸 수 있다.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('wardrobe', 'wardrobe', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "wardrobe read own" on storage.objects;
create policy "wardrobe read own" on storage.objects for select to authenticated
    using (bucket_id = 'wardrobe' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "wardrobe upload own" on storage.objects;
create policy "wardrobe upload own" on storage.objects for insert to authenticated
    with check (bucket_id = 'wardrobe' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "wardrobe update own" on storage.objects;
create policy "wardrobe update own" on storage.objects for update to authenticated
    using (bucket_id = 'wardrobe' and (storage.foldername(name))[1] = (select auth.uid())::text)
    with check (bucket_id = 'wardrobe' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "wardrobe delete own" on storage.objects;
create policy "wardrobe delete own" on storage.objects for delete to authenticated
    using (bucket_id = 'wardrobe' and (storage.foldername(name))[1] = (select auth.uid())::text);
