-- ------------------------------------------------------------ 한 거래로 처리하는 DB 함수 (앱이 rpc 로 부른다)
-- 함수 한 번 = 거래 하나라 중간에 실패하면 함께 되돌아간다. security invoker: 부른 사용자 권한으로 돌아서
-- 위의 RLS 가 그대로 적용되고, 사용자는 auth.uid() 로만 정한다 (다른 사람 id를 넘길 방법이 없음).

-- '샀어요': 후보 빼기 + 옷장 넣기. 이미 뺀 후보면 빈 결과 → 두 번 누르거나, 응답을 못 받고 다시 눌러도 옷은 한 벌.
create or replace function public.buy_candidate(p_candidate_id bigint, p_created_at text)
returns table (new_item_id bigint)
language plpgsql security invoker set search_path = ''
as $$
declare
    c public.purchase_candidates;
begin
    update public.purchase_candidates pc set deleted = 1
     where pc.id = p_candidate_id and pc.user_id = auth.uid() and pc.deleted = 0
    returning pc.* into c;
    if not found then
        return;
    end if;
    return query
    insert into public.wardrobe_items as w (user_id, name, category, subcategory, color, warmth, rain_ok, material,
                                            image_path, notes, ai_category, ai_subcategory, ai_confidence, created_at)
    values (c.user_id, c.name, c.category, c.subcategory, c.color, c.warmth, c.rain_ok, '',
            coalesce(c.image_path, ''), coalesce(c.link, ''), null, c.ai_subcategory, c.ai_confidence, p_created_at)
    returning w.id;
end $$;

-- 추천 세션 + 결과(TOP 3)를 한 묶음으로 저장. 같은 p_request_id 로 다시 부르면 새로 넣지 않고 처음 묶음을 돌려준다.
-- p_results: [{"score": 0.9, "pieces_json": "...", "reasons_json": "...", "components_json": "..."}, ...] (순위순)
create or replace function public.save_recommendation_session(
    p_request_id uuid, p_purpose text, p_temperature double precision, p_apparent_temperature double precision,
    p_humidity double precision, p_precipitation double precision, p_rain integer, p_wind_speed double precision,
    p_weather_source text, p_started_at text, p_results jsonb)
returns table (new_session_id bigint, new_recommendation_ids bigint[])
language plpgsql security invoker set search_path = ''
as $$
declare
    sid bigint;
begin
    insert into public.recommendation_sessions as s (user_id, request_id, purpose, temperature, apparent_temperature,
                                                     humidity, precipitation, rain, wind_speed, weather_source, started_at)
    values (auth.uid(), p_request_id, p_purpose, p_temperature, p_apparent_temperature, p_humidity, p_precipitation,
            p_rain, p_wind_speed, p_weather_source, p_started_at)
    on conflict (user_id, request_id) do nothing
    returning s.id into sid;
    if sid is null then           -- 이미 저장한 요청
        select s.id into sid from public.recommendation_sessions s
         where s.user_id = auth.uid() and s.request_id = p_request_id;
    else
        insert into public.recommendations (user_id, session_id, rank, score, pieces_json, reasons_json,
                                            components_json, created_at)
        select auth.uid(), sid, r.ord, (r.v ->> 'score')::double precision, r.v ->> 'pieces_json',
               r.v ->> 'reasons_json', r.v ->> 'components_json', p_started_at
          from jsonb_array_elements(p_results) with ordinality as r(v, ord);
    end if;
    return query
    select sid, coalesce(array_agg(x.id order by x.rank), '{}'::bigint[])
      from public.recommendations x where x.session_id = sid;
end $$;

-- 사진 여러 장 등록(직접 추가) 묶음 저장. 한 거래라 중간에 실패하면 아무것도 안 바뀐다 (core/db.py 와 같은 규칙):
-- 같은 요청 id 행이 없으면 넣고, 있으면 아직 등록 상태 그대로일 때만(지우지 않았고 '정보 수정'으로 고치지 않음)
-- 보낸 값으로 고친다. 그 밖의 행은 그대로 두고 kept_as_is = true. 묶음 안 반복은 차례로 처리해 나중 값이 남는다.
-- p_rows: [{"request_id": "...", "name": ..., "category": ..., ...}, ...] (모든 행에 요청 id, 순서대로 한 줄씩 결과)
create or replace function public.save_wardrobe_items(p_rows jsonb)
returns table (req uuid, item_id bigint, kept_as_is boolean)
language plpgsql security invoker set search_path = ''
as $$
declare
    r jsonb;
    old public.wardrobe_items;
    new_id bigint;
    changed integer;
begin
    for r in select x.value from jsonb_array_elements(p_rows) as x loop
        select * into old from public.wardrobe_items w
         where w.user_id = auth.uid() and w.request_id = (r ->> 'request_id')::uuid;
        if not found then
            insert into public.wardrobe_items as w (user_id, request_id, name, category, subcategory, color, warmth,
                rain_ok, material, image_path, notes, ai_category, ai_subcategory, ai_confidence, created_at)
            values (auth.uid(), (r ->> 'request_id')::uuid, r ->> 'name', r ->> 'category', r ->> 'subcategory',
                    r ->> 'color', (r ->> 'warmth')::integer, (r ->> 'rain_ok')::integer, r ->> 'material',
                    r ->> 'image_path', r ->> 'notes', r ->> 'ai_category', r ->> 'ai_subcategory',
                    (r ->> 'ai_confidence')::double precision, r ->> 'created_at')
            returning w.id into new_id;
            return query select (r ->> 'request_id')::uuid, new_id, false;
        else
            -- 고치기 조건은 UPDATE 자체에 둔다: 읽은 뒤 다른 창에서 '정보 수정'·삭제가 끼어들어도(먼저 커밋되면
            -- PostgreSQL 이 최신 행으로 조건을 다시 본다) 덮어쓰지 않고, 실제로 바뀐 행이 없으면 kept_as_is = true
            update public.wardrobe_items w
               set name = r ->> 'name', category = r ->> 'category', subcategory = r ->> 'subcategory',
                   color = r ->> 'color', warmth = (r ->> 'warmth')::integer, rain_ok = (r ->> 'rain_ok')::integer,
                   material = r ->> 'material', image_path = r ->> 'image_path', notes = r ->> 'notes',
                   ai_category = r ->> 'ai_category', ai_subcategory = r ->> 'ai_subcategory',
                   ai_confidence = (r ->> 'ai_confidence')::double precision, created_at = r ->> 'created_at'
             where w.id = old.id and w.deleted = 0 and w.edited_at is null;
            get diagnostics changed = row_count;
            return query select (r ->> 'request_id')::uuid, old.id, changed = 0;
        end if;
    end loop;
end $$;

